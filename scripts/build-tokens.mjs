// Generates packages/tokens/tokens.css from docs/design-system/tokens.json (the single source of truth).
import { readFileSync, writeFileSync } from 'node:fs';

const t = JSON.parse(readFileSync(new URL('../docs/design-system/tokens.json', import.meta.url), 'utf8'));
const resolve = (v) =>
  typeof v === 'string' && v.startsWith('{')
    ? v.slice(1, -1).split('.').reduce((o, k) => o[k], t.color)
    : v;
const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const themeVars = (th) => Object.entries(th).map(([k, v]) => `  --${kebab(k)}: ${resolve(v)};`).join('\n');

const st = t.font.style;
const ff = { display: `'${t.font.family.display}', system-ui, sans-serif`, body: `'${t.font.family.body}', system-ui, sans-serif`, mono: `'${t.font.family.mono}', ui-monospace, monospace` };
const out = [];
out.push('/* GENERATED by scripts/build-tokens.mjs from docs/design-system/tokens.json — do not edit */');
out.push(':root {');
out.push(`  --ff-display: ${ff.display};\n  --ff-body: ${ff.body};\n  --ff-mono: ${ff.mono};`);
for (const [k, s] of Object.entries(st)) {
  if (!s.size) continue;
  out.push(`  --fs-${kebab(k)}: ${s.size}px; --lh-${kebab(k)}: ${s.lineHeight}px; --fw-${kebab(k)}: ${s.weight};`);
}
for (const [k, v] of Object.entries(t.space)) out.push(`  --space-${String(k).replace('.', '_')}: ${v}px;`);
for (const [k, v] of Object.entries(t.radius)) out.push(`  --radius-${k}: ${v}px;`);
for (const [k, v] of Object.entries(t.size.control)) out.push(`  --control-${k}: ${v}px;`);
for (const [k, v] of Object.entries(t.elevation)) out.push(`  --elevation-${k}: ${v};`);
for (const [k, v] of Object.entries(t.motion)) out.push(`  --motion-${k}: ${v};`);
out.push(`  --brand-ribbon: ${t.gradient.brandRibbon.value};`);
out.push(`  --logo-tile: ${t.color.neutral['0']}; /* logo always sits on white (02-design-system §4, Q-B3) */`);
out.push(themeVars(t.theme.light));
out.push('  color-scheme: light;');
out.push('}');
out.push(`@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${themeVars(t.theme.dark).replace(/^/gm, '  ')}\n    color-scheme: dark;\n  }\n}`);
out.push(`:root[data-theme="dark"] {\n${themeVars(t.theme.dark)}\n  color-scheme: dark;\n}`);
// Printed documents (PO letter, acknowledgement) are always on white paper, whatever the screen theme.
out.push(`@media print {\n  :root, :root[data-theme="dark"], :root:not([data-theme="light"]) {\n${themeVars(t.theme.light).replace(/^/gm, '  ')}\n    color-scheme: light;\n  }\n}`);
writeFileSync(new URL('../packages/tokens/tokens.css', import.meta.url), out.join('\n') + '\n');
console.log('tokens.css written');
