<script lang="ts">
  // NT-03: export any list. CSV is generated in the browser; Excel and PDF are rendered server-side in the real build.
  import { say } from '@btw/ui';
  import Download from '@lucide/svelte/icons/download';
  let { name, rows }: { name: string; rows: () => (string | number)[][] } = $props();
  let el: HTMLDetailsElement;
  function csv() {
    const esc = (v: string | number) => { const s = String(v ?? ''); return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; };
    const blob = new Blob([rows().map((r) => r.map(esc).join(',')).join('\n')], { type: 'text/csv' });
    const a = Object.assign(document.createElement('a'), { href: URL.createObjectURL(blob), download: `${name}-${new Date().toISOString().slice(0, 10)}.csv` });
    a.click(); URL.revokeObjectURL(a.href); el.open = false; say('CSV downloaded');
  }
  function server(fmt: string) { el.open = false; say(`${fmt} export is generated by the server in the real build (NT-03)`); }
</script>
<details class="menu" bind:this={el}>
  <summary class="btn btn-secondary"><Download size={16} />Export</summary>
  <div class="pop" role="menu">
    <button role="menuitem" onclick={csv}>CSV</button>
    <button role="menuitem" onclick={() => server('Excel')}>Excel (.xlsx)</button>
    <button role="menuitem" onclick={() => server('PDF')}>PDF</button>
  </div>
</details>
<style>
  .menu { position: relative; }
  summary { list-style: none; }
  summary::-webkit-details-marker { display: none; }
