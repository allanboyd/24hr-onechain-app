// V3-12 step 2: Record payment on Sales; Management counts it. Run: node tests/design-v3/payments.mjs <base> <outDir>
import { chromium } from 'playwright';
const [base, out = '.'] = process.argv.slice(2);
let fails = 0; const ok = (c, m) => { console.log(`${c ? 'ok  ' : 'FAIL'} ${m}`); if (!c) fails++; };
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(base, { waitUntil: 'domcontentloaded' });
await p.getByRole('button', { name: 'Sign in to the web as Daniel' }).first().click(); await p.locator('aside nav a').first().waitFor();
const received = async () => {
  await p.goto(`${base}#/management/cash`); await p.locator('.mrep .kpi').first().waitFor({ timeout: 20_000 }); await p.waitForTimeout(800);
  const t = await p.locator('.mrep .kpi', { hasText: /received/i }).first().locator('.val').textContent();
  return Number((t ?? '').replace(/[^0-9.-]/g, ''));
};
const before = await received();
await p.goto(`${base}#/sales?status=Unpaid`); await p.waitForTimeout(2500);
const btn = p.getByRole('button', { name: /^Record payment for / }).first();
ok(await btn.count() === 1, 'an unpaid sale has a Record payment button');
const label = await btn.getAttribute('aria-label');
await btn.click(); await p.locator('dialog[open]').waitFor();
const owes = Number(((await p.locator('dialog[open] .caption strong').textContent()) ?? '').replace(/[^0-9.]/g, ''));
const amt = Math.max(1, Math.floor(owes / 2));
ok(owes > 0 && Number(await p.locator('dialog[open] input[type=number]').inputValue()) === owes, `the form starts at what is still owed (USD ${owes})`);
await p.locator('dialog[open] input[type=number]').fill(String(owes + 10));
await p.getByRole('button', { name: 'Record payment', exact: true }).click(); await p.waitForTimeout(800);
ok(await p.locator('dialog[open]').count() === 1, 'more than the balance is not accepted');
await p.locator('dialog[open] input[type=number]').fill(String(amt));
await p.locator('dialog[open] select').selectOption('Mobile money');
await p.locator('dialog[open] input[placeholder^="Receipt"]').fill('MM-777');
await p.screenshot({ path: `${out}/sales-record-payment.png` });
await p.getByRole('button', { name: 'Record payment', exact: true }).click(); await p.waitForTimeout(1500);
ok(await p.locator('dialog[open]').count() === 0, `USD ${amt} recorded (${label})`);
await p.goto(`${base}#/sales?cust=${encodeURIComponent((label ?? '').replace('Record payment for ', ''))}`); await p.waitForTimeout(2000);
ok(await p.locator('table tbody tr').first().getByText('Part-paid').count() === 1, 'the sale shows Part-paid');
const after = await received();
ok(Math.abs(after - before - amt) <= 1, `Management → Cash and closing: received went up by USD ${amt} (${before} → ${after})`);
await p.goto(`${base}#/management/clients`); await p.locator('.mrep .methods').first().waitFor({ timeout: 20_000 });
ok(await p.locator('.mrep .methods li', { hasText: 'Mobile money' }).count() === 1, 'Management → Sales and clients: money by how clients paid shows Mobile money');
ok(!errs.length, `no page errors ${errs.join(' | ')}`);
await b.close();
console.log(fails ? `${fails} check(s) failed` : 'all payments checks passed');
process.exit(fails ? 1 : 0);
